// Regenerates src/lib/monaco-features.ts from monaco-editor's own
// editor.main.js: every editor feature, minus its 80+ bundled languages and
// the TS/CSS/HTML/JSON language services we don't use. Run after upgrading
// monaco-editor.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "node_modules/monaco-editor/package.json"), "utf8"));
const main = readFileSync(join(root, "node_modules/monaco-editor/esm/vs/editor/editor.main.js"), "utf8");

const imports = [...main.matchAll(/^import '([^']+)';$/gm)]
  .map((m) => m[1])
  .filter((p) => !p.includes("languages/definitions/"))
  // "monaco-esm" is a Vite/TS alias for node_modules/monaco-editor/esm/vs
  .map((p) => "monaco-esm/" + join("editor", p).replace(/\.js$/, ""));

const out = [
  `// Generated by scripts/gen-monaco-features.mjs from monaco-editor ${pkg.version}. Do not edit.`,
  ...imports.map((p) => `import "${p}";`),
  "",
].join("\n");
writeFileSync(join(root, "src/lib/monaco-features.ts"), out);
console.log(`wrote ${imports.length} imports`);
